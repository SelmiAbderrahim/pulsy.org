import { readFileSync } from "node:fs";
import i18next from "i18next";
import { I18nextProvider } from "react-i18next";
import { act, cleanup, render, screen } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { toast, pauseToasts } from "@/lib/toast";
import { Toaster } from "./sonner";

afterEach(() => { toast.dismiss(); cleanup(); vi.unstubAllGlobals(); vi.useRealTimers(); });
it.each(["en", "ar", "fr", "de", "es"])("renders translated toast controls in %s without language fallback", async language => {
  vi.stubGlobal("matchMedia", () => ({ matches: false, addEventListener() {}, removeEventListener() {} }));
  const common = JSON.parse(readFileSync(`public/locales/${language}/common.json`, "utf8"));
  const i18n = i18next.createInstance();
  await i18n.init({ lng: language, fallbackLng: false, resources: { [language]: { common } }, defaultNS: "common" });
  render(<I18nextProvider i18n={i18n}><Toaster /></I18nextProvider>);
  act(() => { toast.success(common.actions.save, { duration: Infinity }); });
  expect(await screen.findByRole("button", { name: common.actions.close })).toBeVisible();
  expect(document.querySelector("[data-sonner-toaster]")).toHaveAttribute("dir", language === "ar" ? "rtl" : "ltr");
  expect(document.querySelector("[data-sonner-toaster]")).toHaveAttribute("data-y-position", "bottom");
  expect(document.querySelector("[data-sonner-toaster]")).toHaveAttribute("data-x-position", language === "ar" ? "left" : "right");
  expect(document.querySelector("section")?.getAttribute("aria-label")).toBe(`${common.nav.notifications} alt+T`);
  const text = [...document.querySelectorAll("*")].flatMap(el => [el.getAttribute("aria-label"), el.getAttribute("title"), ...[...el.childNodes].filter(node => node.nodeType === Node.TEXT_NODE).map(node => node.textContent?.trim())]);
  expect(text.filter(value => value && /^[a-z]+(\.[a-zA-Z]+)+$/.test(value))).toEqual([]);
});
it.each(["light", "dark"])("uses theme tokens and a separate action row in %s", async theme => {
  document.documentElement.classList.toggle("dark", theme === "dark");
  vi.stubGlobal("matchMedia", () => ({ matches: false, addEventListener() {}, removeEventListener() {} }));
  const i18n = i18next.createInstance();
  await i18n.init({ lng: "en", resources: { en: { common: { actions: { close: "Close" }, nav: { notifications: "Notifications" } } } }, defaultNS: "common" });
  render(<I18nextProvider i18n={i18n}><Toaster /></I18nextProvider>);
  vi.useFakeTimers({ toFake: ["setTimeout", "clearTimeout", "Date", "requestAnimationFrame", "cancelAnimationFrame"] });
  act(() => { toast.success("Monitor added", { action: { label: "View monitor", onClick: vi.fn() } }); });
  await act(async () => { await vi.advanceTimersByTimeAsync(1); });
  const action = screen.getByRole("button", { name: "View monitor" });
  const toastElement = action.closest("[data-sonner-toast]");
  expect(toastElement).toHaveClass("group-[.toaster]:bg-popover", "group-[.toaster]:text-popover-foreground");
  expect(action).toHaveClass("!col-start-2", "!row-start-2");
  act(() => { pauseToasts(true); });
  await act(async () => { await vi.advanceTimersByTimeAsync(15000); });
  expect(action).toBeInTheDocument();
  act(() => { pauseToasts(false); });
  await act(async () => { await vi.advanceTimersByTimeAsync(9000); });
  expect(action).toBeInTheDocument();
  await act(async () => { await vi.advanceTimersByTimeAsync(1300); });
  await act(async () => { await vi.advanceTimersByTimeAsync(400); });
  expect(screen.queryByRole("button", { name: "View monitor" })).toBeNull();
  act(() => {
    const first = toast.success("One");
    expect(toast.success("One")).toBe(first);
    toast.info("Two"); toast.warning("Three"); toast.error("Queued error");
  });
  await act(async () => { await vi.advanceTimersByTimeAsync(1); });
  expect(document.querySelectorAll("[data-sonner-toast]")).toHaveLength(3);
  expect(screen.queryByText("Queued error")).toBeNull();
  await act(async () => { await vi.advanceTimersByTimeAsync(5300); });
  expect(screen.getByText("Queued error")).toBeInTheDocument();
  expect(screen.getByText("Queued error").closest("[data-sonner-toast]")).toHaveAttribute("aria-live", "assertive");
  document.documentElement.classList.remove("dark");
});
